-- 1. Find Nearby Complaints within Radius (for Duplicate Detection)
CREATE OR REPLACE FUNCTION get_nearby_complaints(
  p_lat DOUBLE PRECISION,
  p_lng DOUBLE PRECISION,
  p_radius_meters INT DEFAULT 100
)
RETURNS TABLE (
  id BIGINT,
  public_id TEXT,
  category TEXT,
  status TEXT,
  distance_meters DOUBLE PRECISION
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    c.id,
    c.public_id,
    c.category,
    c.status,
    ST_Distance(
      c.geom::geography,
      ST_SetSRID(ST_MakePoint(p_lng, p_lat), 4326)::geography
    ) AS distance_meters
  FROM complaints c
  WHERE c.geom IS NOT NULL
    AND c.status != 'resolved'
    AND ST_DWithin(
      c.geom::geography,
      ST_SetSRID(ST_MakePoint(p_lng, p_lat), 4326)::geography,
      p_radius_meters
    )
  ORDER BY distance_meters ASC;
END;
$$ LANGUAGE plpgsql;
